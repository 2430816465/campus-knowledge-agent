"""Build native 24 fps sprites; never synthesize temporal frames."""
from pathlib import Path
import json, math, hashlib
import cv2
import numpy as np
from PIL import Image, ImageDraw

ROOT=Path(__file__).resolve().parents[1]
QC=ROOT/'artifacts/hero-video'
OUT=ROOT/'games/coop/assets/art-video'
OUT.mkdir(exist_ok=True)
native=[np.array(Image.open(QC/'native'/f'{i:03}.png').convert('RGBA')) for i in range(241)]
source_ranges={'idle':list(range(180,204)), 'start':list(range(42,49)), 'run':list(range(79,127)), 'stop':list(range(165,180))}
clips={action:[native[i] for i in indices] for action,indices in source_ranges.items()}

def error(a,b): return float(np.mean(np.abs(a.astype(float)-b.astype(float))))
run_start=min(range(len(clips['run'])),key=lambda i:error(clips['start'][-1],clips['run'][i]))
stop_entries=[min(range(6),key=lambda j:error(im,clips['stop'][j])) for im in clips['run']]
meta={'source':'勇者跑步.mp4','sourceFps':24,'fps':24,'nativeFramesOnly':True,'interpolation':'none; original video frames only','stopFromStart':6, 'cell':160,'columns':8,'drawCell':80,'anchorX':40,'anchorY':74,'runEntry':run_start,'stopEntries':stop_entries,'clips':{}}
preview=[]
for action,frames in clips.items():
    count=len(frames);sheet=Image.new('RGBA',(8*160,math.ceil(count/8)*160))
    for i,im in enumerate(frames): sheet.paste(Image.fromarray(im),(i%8*160,i//8*160))
    sheet.save(OUT/f'{action}.png',optimize=True)
    for i,source in enumerate(source_ranges[action]):
        actual=np.array(sheet.crop((i%8*160,i//8*160,i%8*160+160,i//8*160+160)))
        assert np.array_equal(actual,native[source]), (action,source)

    rgb=np.array(sheet);hsv=cv2.cvtColor(rgb[:,:,:3],cv2.COLOR_RGB2HSV)
    blue=(hsv[:,:,0]>93)&(hsv[:,:,0]<137)&(hsv[:,:,1]>75)&(rgb[:,:,3]>0)
    hsv[blue,0]=21;hsv[blue,1]=(hsv[blue,1]*.8).astype('uint8')
    gold=cv2.cvtColor(hsv,cv2.COLOR_HSV2RGB);rgb[blue,:3]=gold[blue]
    Image.fromarray(rgb).save(OUT/f'{action}-gold.png',optimize=True)
    differences=[error(frames[i],frames[(i+1)%count]) for i in range(count)]
    bounds=[Image.fromarray(f).getbbox() for f in frames]
    meta['clips'][action]={'count':count,'sourceFrames':source_ranges[action],'uniqueFrames':len({hashlib.sha256(f.tobytes()).hexdigest() for f in frames}),'seamError':differences[-1],'medianStepError':float(np.median(differences)),'bounds':bounds}
    assert all(b and b[0]>0 and b[1]>0 and b[2]<160 and b[3]<160 for b in bounds),action
    for im in frames:
        bg=Image.new('RGB',(320,320),'#33485b');p=Image.fromarray(im).resize((320,320),Image.Resampling.NEAREST);bg.paste(p,(0,0),p);preview.append(bg)
# Preview preserves the native source timing.
preview[0].save(QC/'idle-run-stop-preview.png',save_all=True,append_images=preview[1:],duration=1000/24,loop=0)
contact=Image.new('RGB',(8*160,6*180),'#33485b');d=ImageDraw.Draw(contact)
for i,im in enumerate(clips['run']):
    p=Image.fromarray(im);x=i%8*160;y=i//8*180;contact.paste(p,(x,y),p);d.text((x+5,y+160),'source '+str(source_ranges['run'][i]),fill='white')
contact.save(QC/'run-native-contact.png')
(OUT/'manifest.json').write_text(json.dumps(meta,indent=2),encoding='utf8')
(QC/'summary.json').write_text(json.dumps({**meta,'clips':{k:{f:v for f,v in c.items() if f!='bounds'} for k,c in meta['clips'].items()}},indent=2),encoding='utf8')
config={k:meta[k] for k in ['fps','cell','columns','drawCell','runEntry','stopEntries','stopFromStart']}
config['clips']={k:v['count'] for k,v in meta['clips'].items()}
(ROOT/'games/coop/src/hero-video-config.js').write_text('// Generated by tools/build-hero-video-atlas.py from the supplied video.\n(function(){\nconst a=window.RushArtConfig;\na.hero.video='+json.dumps(config,separators=(',',':'))+';\nfor(const action of Object.keys(a.hero.video.clips)){a.files[action]="../art-video/"+action+".png";a.files[action+"Gold"]="../art-video/"+action+"-gold.png";}\n})();\n',encoding='utf8')
print('runEntry',run_start,'stopEntries',stop_entries)
